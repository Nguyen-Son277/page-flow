import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { hashPassword } from '../src/lib/security';
import { randomUUID } from 'node:crypto';
const db = new PrismaClient();
const fixture = `browser-${randomUUID()}`; let userId: string, pageId: string;
test.beforeAll(async () => {
  if (process.env.RUN_DB_TESTS !== 'true') throw new Error('Browser test requires isolated database and RUN_DB_TESTS=true');
  const user = await db.user.create({ data: { email: `${fixture}@test.local`, name: 'Browser Admin', role: 'ADMIN', passwordHash: hashPassword('browser-test-password') } }); userId = user.id;
  const page = await db.page.create({ data: { metaId: fixture, name: 'Browser Demo Page', demo: true, connection: 'DEMO' } }); pageId = page.id;
  const at = new Date();
  const c = await db.conversation.create({ data: { pageId, psid: 'browser-customer', customerName: 'Khách Kiểm Thử', preview: 'Xin chào', lastCustomerAt: at, lastIncomingAt: at, lastMessageAt: at } });
  await db.message.create({ data: { conversationId: c.id, role: 'CUSTOMER', text: 'Xin chào', receivedAt: at } });
});
test.afterAll(async () => { await db.page.deleteMany({ where: { id: pageId } }); await db.auditLog.deleteMany({ where: { userId } }); await db.user.deleteMany({ where: { id: userId } }); await db.$disconnect(); });
test('login, inbox, takeover, send, knowledge and mobile', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/login'); await page.getByLabel('Email hoặc tên đăng nhập').fill(`${fixture}@test.local`); await page.getByLabel('Mật khẩu', { exact: true }).fill('browser-test-password');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page.getByText('Browser Demo Page', { exact: true }).first()).toBeVisible();
  await page.getByRole('button').filter({ hasText: 'Khách Kiểm Thử' }).click();
  await expect(page.getByRole('heading', { name: 'Khách Kiểm Thử' })).toBeVisible();
  await page.getByRole('button', { name: 'Tiếp quản', exact: true }).click();
  await expect(page.getByText('Bạn đang kiểm soát hội thoại')).toBeVisible();
  await page.getByLabel('Nội dung trả lời').fill('Tin nhắn kiểm thử từ nhân viên');
  await page.getByRole('button', { name: 'Gửi tin nhắn', exact: true }).click();
  await expect(page.getByText('Tin nhắn kiểm thử từ nhân viên', { exact: true })).toBeVisible();
  await expect(page.getByText('Mô phỏng · Không gửi Facebook', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Trả lại AI', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await expect(page.getByText('AI đang tắt trên Page này')).toBeVisible();
  await page.screenshot({ path: 'artifacts/inbox-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Tri thức AI', exact: true }).first().click();
  await expect(page.getByRole('heading', { name: /Tri thức|kiến thức/i }).first()).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});
